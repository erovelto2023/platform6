// ─── Helper Functions ─────────────────────────────────────────────
export function getPresetById(id: string): SpacePreset | undefined {
    return SPACE_PRESETS.find((p) => p.id === id);
}

export function getPresetsByCategory(category: SpaceCategory): SpacePreset[] {
    return SPACE_PRESETS.filter((p) => p.category === category);
}

export function searchPresets(query: string): SpacePreset[] {
    const q = query.toLowerCase();
    return SPACE_PRESETS.filter(
        (p) =>
            p.name.toLowerCase().includes(q) ||
            p.description.toLowerCase().includes(q) ||
            p.category.toLowerCase().includes(q) ||
            p.type.toLowerCase().includes(q)
    );
}
